// Окно, в котором Home ищет следующий план. 60 дней даёт хороший trade-off:
// большинство пар планируют события на ближайший месяц-два, а лишние строки
// не блокируют prefetch hit. Используется и page-prefetch'ом, и HomeNextPlan
// — обе стороны должны держать одно значение, иначе queryKey разъедется и
// клиент сделает лишний refetch.
export const HOME_NEXT_PLAN_RANGE_DAYS = 60;
